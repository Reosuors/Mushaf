data class Surah(
    val number: Int,
    val arabic: String,
    val english: String,
    val urdu: String,
    val bengali: String,
    val verses: Int,
    val type: String // "مكية" / "مدنية"
) {
    fun localizedName(lang: String): String = when (lang) {
        "en" -> english
        "ur" -> urdu
        "bn" -> bengali
        else -> arabic
    }
    
    fun localizedType(lang: String): String = when (lang) {
        "en" -> if (type == "مكية") "Meccan" else "Medinan"
        "ur" -> if (type == "مكية") "مکی" else "مدنی"
        "bn" -> if (type == "مكية") "মাক্কী" else "মাদানী"
        else -> type
    }
}

